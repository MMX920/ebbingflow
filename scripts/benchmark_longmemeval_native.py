"""Run stripped LongMemEval inputs through the open-source EbbingFlow stack.

The input file must contain user messages, timestamps, and final questions
only. Official assistant messages and official answers are neither accepted
nor used. Every reply is generated by EbbingFlow's normal chat path.
"""

from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import math
import statistics
import time
import uuid
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any


def parse_date(value: str) -> datetime:
    raw = str(value or "").strip()
    if not raw:
        return datetime.now(timezone.utc)
    if "(" in raw and ")" in raw:
        raw = (raw[: raw.index("(")] + raw[raw.index(")") + 1 :]).strip()
    for fmt in ("%Y/%m/%d %H:%M", "%Y-%m-%d %H:%M:%S", "%Y-%m-%dT%H:%M:%S%z"):
        try:
            parsed = datetime.strptime(raw, fmt)
            return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)
        except ValueError:
            continue
    parsed = datetime.fromisoformat(raw.replace("Z", "+00:00"))
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)


def validate_stripped_dataset(dataset: list[dict[str, Any]]) -> None:
    for case in dataset:
        if "answer" in case:
            raise ValueError(f"official answer present in case {case.get('question_id')}")
        for session in case.get("haystack_sessions") or []:
            for turn in session or []:
                if str(turn.get("role") or "") != "user":
                    raise ValueError(
                        f"non-user history message present in case {case.get('question_id')}"
                    )


def _session_id(question_id: str, official_session_id: str) -> str:
    digest = hashlib.sha1(f"{question_id}:{official_session_id}".encode("utf-8")).hexdigest()[:20]
    return f"lme_open_{digest}"


def _memory_snapshot(canvas: dict[str, Any]) -> list[dict[str, Any]]:
    rows = []
    for item in list(canvas.get("rag_context_structured") or [])[:10]:
        if not isinstance(item, dict):
            continue
        rows.append(
            {
                "content": str(item.get("content") or "")[:800],
                "source_type": item.get("source_type"),
                "source_name": item.get("source_name"),
                "score": item.get("final_score"),
                "in_prompt": item.get("in_prompt"),
                "source_msg_id": item.get("source_msg_id"),
                "evidence_context": str(item.get("evidence_context") or "")[:1600],
            }
        )
    return rows


async def _generate_turn(*, session: Any, text: str, timestamp: str) -> dict[str, Any]:
    from core.chat_engine import get_standard_engine
    from core.monitoring import token_monitor

    started = time.perf_counter()
    first_content_ms: float | None = None
    parts: list[str] = []
    error: str | None = None
    try:
        async for chunk in get_standard_engine().chat_stream(text, session, simulated_at=timestamp):
            if chunk:
                parts.append(chunk)
                if first_content_ms is None:
                    first_content_ms = (time.perf_counter() - started) * 1000
    except Exception as exc:
        error = f"{type(exc).__name__}: {exc}"
    full_ms = (time.perf_counter() - started) * 1000
    response = "".join(parts)
    if "[AI 响应异常:" in response and error is None:
        error = response
    canvas = dict(session.context_canvas or {})
    return {
        "timestamp": timestamp,
        "user_input": text,
        "assistant_response": response,
        "error": error,
        "first_content_ms": round(first_content_ms or full_ms, 1),
        "full_response_ms": round(full_ms, 1),
        "tokens": token_monitor.get_report_data(),
        "retrieved_memories": _memory_snapshot(canvas),
    }


async def _event_count(owner_id: str) -> int:
    from memory.sql.pool import get_db

    async with get_db() as conn:
        is_sqlite = "sqlite" in str(type(conn)).lower()
        if is_sqlite:
            cursor = await conn.execute(
                "SELECT COUNT(*) FROM ef_memory_events WHERE owner_id = ?",
                (owner_id,),
            )
            row = await cursor.fetchone()
            return int(row[0] if row else 0)
        return int(
            await conn.fetchval(
                "SELECT COUNT(*) FROM ef_memory_events WHERE owner_id = $1",
                owner_id,
            )
            or 0
        )


async def _run_case(case: dict[str, Any]) -> dict[str, Any]:
    from core.session import ChatSession
    from memory.history.repository import SqlHistoryRepository

    question_id = str(case.get("question_id") or "case")
    owner_id = f"bench_open_{question_id[-12:]}_{uuid.uuid4().hex[:8]}"[:64]
    history: list[dict[str, Any]] = []
    dated_sessions = list(
        zip(
            case.get("haystack_dates") or [],
            case.get("haystack_session_ids") or [],
            case.get("haystack_sessions") or [],
        )
    )
    dated_sessions.sort(key=lambda item: parse_date(str(item[0])))
    for session_date, official_session_id, turns in dated_sessions:
        base_time = parse_date(str(session_date))
        session = ChatSession(
            session_id=_session_id(question_id, str(official_session_id)),
            user_id=owner_id,
            history_repo=SqlHistoryRepository(),
        )
        await session.restore_from_repo()
        for index, turn in enumerate(turns or []):
            timestamp = (base_time + timedelta(seconds=index * 2)).isoformat()
            row = await _generate_turn(
                session=session,
                text=str(turn.get("content") or ""),
                timestamp=timestamp,
            )
            row["official_session_id"] = str(official_session_id)
            history.append(row)

    final_session = ChatSession(
        session_id=f"final_{question_id}_{uuid.uuid4().hex[:8]}",
        user_id=owner_id,
        history_repo=SqlHistoryRepository(),
    )
    await final_session.restore_from_repo()
    final = await _generate_turn(
        session=final_session,
        text=str(case.get("question") or ""),
        timestamp=parse_date(str(case.get("question_date") or "")).isoformat(),
    )
    return {
        "question_id": question_id,
        "question_type": case.get("question_type"),
        "is_abstention": question_id.endswith("_abs"),
        "question": case.get("question"),
        "final_answer": final["assistant_response"],
        "final_error": final["error"],
        "first_content_ms": final["first_content_ms"],
        "full_response_ms": final["full_response_ms"],
        "final_tokens": final["tokens"],
        "retrieved_memories": final["retrieved_memories"],
        "history_session_count": len(dated_sessions),
        "history_user_turn_count": len(history),
        "history_failed_turn_count": sum(bool(row.get("error")) for row in history),
        "history_turn_response_ms_mean": round(
            statistics.mean(float(row.get("full_response_ms") or 0) for row in history), 1
        ) if history else 0.0,
        "memory_event_count": await _event_count(owner_id),
        "generated_history": history,
    }


def _p95(values: list[float]) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    return round(ordered[max(0, math.ceil(len(ordered) * 0.95) - 1)], 1)


def build_report(dataset_path: Path, selected: list[dict], results: list[dict], started: float) -> dict[str, Any]:
    completed = [row for row in results if not row.get("error")]
    history_ms = [
        float(turn.get("full_response_ms") or 0)
        for row in completed
        for turn in row.get("generated_history") or []
    ]
    final_ms = [float(row.get("full_response_ms") or 0) for row in completed]
    return {
        "benchmark": "LongMemEval EbbingFlow Open Source Native",
        "evaluation_contract": {
            "official_user_messages_replayed": True,
            "official_timestamps_replayed": True,
            "official_assistant_messages_available_to_runtime": 0,
            "official_answers_available_to_runtime": False,
            "automated_judge_used": False,
            "grading": "Codex human review against user inputs and EbbingFlow-generated history",
        },
        "dataset": str(dataset_path),
        "requested_case_count": len(selected),
        "completed_case_count": len(completed),
        "history_user_turn_count": sum(int(row.get("history_user_turn_count") or 0) for row in completed),
        "generated_assistant_turn_count": sum(
            sum(bool(turn.get("assistant_response")) for turn in row.get("generated_history") or [])
            for row in completed
        ),
        "history_failed_turn_count": sum(int(row.get("history_failed_turn_count") or 0) for row in completed),
        "memory_event_count": sum(int(row.get("memory_event_count") or 0) for row in completed),
        "history_response_ms_mean": round(statistics.mean(history_ms), 1) if history_ms else 0.0,
        "history_response_ms_p95": _p95(history_ms),
        "final_response_ms_mean": round(statistics.mean(final_ms), 1) if final_ms else 0.0,
        "final_response_ms_p95": _p95(final_ms),
        "elapsed_seconds": round(time.perf_counter() - started, 1),
        "cases": results,
    }


async def run(args: argparse.Namespace) -> dict[str, Any]:
    dataset = json.loads(args.dataset.read_text(encoding="utf-8"))
    validate_stripped_dataset(dataset)
    selected = list(dataset[: args.limit]) if args.limit > 0 else list(dataset)
    results: list[dict[str, Any]] = []
    started = time.perf_counter()
    for index, case in enumerate(selected, start=1):
        print(f"[{index}/{len(selected)}] {case.get('question_id')} {case.get('question_type')}", flush=True)
        try:
            result = await _run_case(case)
        except Exception as exc:
            result = {
                "question_id": case.get("question_id"),
                "question_type": case.get("question_type"),
                "question": case.get("question"),
                "error": f"{type(exc).__name__}: {exc}",
            }
        results.append(result)
        print(
            f"  turns={result.get('history_user_turn_count')} "
            f"history_errors={result.get('history_failed_turn_count')} "
            f"answer_ms={result.get('full_response_ms')} error={result.get('error')}",
            flush=True,
        )
        report = build_report(args.dataset, selected, results, started)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return build_report(args.dataset, selected, results, started)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--limit", type=int, default=20)
    args = parser.parse_args()
    report = asyncio.run(run(args))
    args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0 if report["completed_case_count"] == report["requested_case_count"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
